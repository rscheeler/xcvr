"""
LO frequency planning for wideband up/down converters.

Built on :mod:`xcvr.spurs`. For a fixed IF band and a mixer spur table it answers:

  * Which LO frequencies leave NO spur inside my output passband (spurs a
    filter cannot remove)?
  * For those LOs, how far from the passband is the nearest spur that needs
    filtering (the "guard band"), and how much rejection must the filter give?
  * What is the filter mask (required rejection vs. frequency)?

Terminology
-----------
  IF band    : [if_lo, if_hi] (Hz or pint Quantity) = the FULL band the hardware must pass.
               The filter passband is this band (translated to the output
               frequency). Nothing inside it can be filtered.
  signal_bw  : width of the signal that occupies the band at any instant
               (e.g. 250 MHz inside a 2 GHz band). It may sit anywhere in
               the band. Default None = signal fills the whole band.
  RF band    : IF +/- LO.   sideband="upper": RF = LO + IF  (RF above LO)
                            sideband="lower": RF = LO - IF  (RF below LO,
                                                             spectrum inverted)
  direction  : "up"   = IF is the mixer input, RF is the output
               "down" = RF is the mixer input, IF is the output
  spec_dbc   : required spur level at the output, dB below the desired signal.
               (For an absolute limit: spec_dbc = P_out_dBm - limit_dBm.)

How spurs are judged
--------------------
A spur is generated by the signal wherever it sits in the band, so each spur
sweeps a band of m x (full band width). Then:

  * spur band OUTSIDE the passband  -> a filter can reject it. Required
    rejection = spec - level, needed from the passband edge outward.
  * spur INSIDE the passband, inside the signal's own channel (co-channel)
    -> cannot be filtered; must meet spec_dbc on its own.
  * spur INSIDE the passband but outside the signal's channel -> cannot be
    filtered by the RF filter; must meet passband_spec_dbc (default = spec_dbc,
    conservative). Set it to 0 if a downstream channel filter removes these.

Spur levels come from a SpurTable (datasheet m x n chart). Spurs overlapping the
passband count at full table level (conservative); use_overlap_fraction=True
applies a modulated-carrier power-spreading estimate instead.

Frequencies are Hz (or pint Quantities); plots and reports auto-scale to kHz/MHz/GHz.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Optional

import numpy as np

from xcvr.spurs import (
    SpurTable,
    compute_spurs,
    fmt_freq,
    freq_unit,
    plot_spur_chart,
    to_hz,
)


# ------------------------------------------------------------------ model
@dataclass
class Converter:
    """One up- or down-converter and its frequency-plan requirements (see module docs).

    ``if_lo``, ``if_hi``, ``signal_bw`` and ``rf_window`` accept Hz floats or pint Quantities
    and are stored in Hz.
    """

    name: str
    if_lo: Any
    if_hi: Any
    direction: str = "up"  # "up" (IF->RF) or "down" (RF->IF)
    sideband: str = "upper"  # "upper": RF=LO+IF, "lower": RF=LO-IF
    spec_dbc: float = 60.0
    table: Optional[SpurTable] = None
    rf_backoff_db: float = 0.0
    rf_window: Optional[tuple] = None  # (lo, hi) RF band must fit inside (Hz)
    max_order: Optional[int] = None
    use_overlap_fraction: bool = False
    signal_bw: Optional[Any] = None  # instantaneous signal width (Hz)
    passband_spec_dbc: Optional[float] = None  # spec for in-passband,
    # out-of-channel spurs
    image_rejection_db: float = 0.0  # image-reject / SSB mixer: internal
    # rejection of the unwanted sideband
    # (up-conversion only; 0 = plain mixer)

    def __post_init__(self):
        if self.direction not in ("up", "down"):
            raise ValueError("direction must be 'up' or 'down'")
        if self.sideband not in ("upper", "lower"):
            raise ValueError("sideband must be 'upper' or 'lower'")
        self.if_lo, self.if_hi = float(to_hz(self.if_lo)), float(to_hz(self.if_hi))
        if self.signal_bw is not None:
            self.signal_bw = float(to_hz(self.signal_bw))
        if self.rf_window is not None:
            self.rf_window = tuple(float(to_hz(v)) for v in self.rf_window)

    @property
    def bw(self) -> float:
        """Full passband width."""
        return self.if_hi - self.if_lo

    @property
    def sig_bw(self) -> float:
        return self.bw if self.signal_bw is None else min(self.signal_bw, self.bw)

    @property
    def pb_spec(self) -> float:
        return self.spec_dbc if self.passband_spec_dbc is None else self.passband_spec_dbc

    def geometry(self, lo):
        """Bands at this LO, or None if impossible (e.g. LO below IF)."""
        if self.sideband == "upper":
            rf = (lo + self.if_lo, lo + self.if_hi)
        else:
            if lo <= self.if_hi:
                return None
            rf = (lo - self.if_hi, lo - self.if_lo)
        ifb = (self.if_lo, self.if_hi)
        if self.direction == "up":
            inp, out = ifb, rf
            sign = 1 if self.sideband == "upper" else -1
        else:
            inp, out, sign = rf, ifb, -1
        ok = True
        if self.rf_window is not None:
            ok = rf[0] >= self.rf_window[0] and rf[1] <= self.rf_window[1]
        return dict(inp=inp, out=out, rf=rf, sign=sign, ok=ok)


def _cochannel(conv: Converter, lo, m, n, s, sign, K=48):
    """True if, for some position of the signal inside the band, this spur
    lands inside that signal's own output channel."""
    w = conv.sig_bw
    if w >= conv.bw - 1e-9:
        return True  # signal fills the band
    q = np.linspace(conv.if_lo + w / 2, conv.if_hi - w / 2, K)  # IF centers
    if conv.direction == "up":
        c_in, c_out = q, np.abs(q + sign * lo)
    else:
        c_in = lo + q if conv.sideband == "upper" else lo - q
        c_out = q
    y = np.abs(m * c_in + s * n * lo)
    return bool(np.any(np.abs(y - c_out) <= (m * w / 2 + w / 2)))


@dataclass
class SpurInfo:
    spur: object
    level: float  # dB below desired output
    rejection: float  # filter rejection / shortfall needed for the spec (dB)
    in_band: bool  # spur band overlaps the passband
    unfilterable: bool  # in passband AND needs rejection -> change the plan
    gap: float  # Hz from passband edge to nearest edge of spur band
    segs: list  # outside-passband extents: (side, near, far) from edge
    co_channel: bool = False
    spec: float = 0.0  # spec this spur is judged against
    inband_seg: Optional[tuple] = None  # (y0, y1) inside passband, relative


@dataclass
class Analysis:
    conv: Converter
    lo: float
    geo: Optional[dict]
    infos: list
    floor_dbc: float

    @property
    def margin(self) -> float:
        """Worst in-passband spur margin vs. its spec (dB). <0 = fails."""
        v = [i.level - i.spec for i in self.infos if i.in_band]
        return min(v) if v else self.floor_dbc - self.conv.spec_dbc

    @property
    def guard(self) -> float:
        """Distance (Hz) from the passband to the nearest spur needing a
        filter. 0 if any in-passband spur violates spec; inf if none."""
        if any(i.unfilterable for i in self.infos):
            return 0.0
        g = [i.gap for i in self.infos if i.rejection > 0 and not i.in_band]
        return min(g) if g else np.inf

    @property
    def max_rej(self) -> float:
        r = [i.rejection for i in self.infos if not i.in_band]
        return max(r) if r else 0.0

    def guard_at(self, rej_db: float) -> float:
        """Distance (Hz) from the passband to the nearest out-of-passband spur
        needing at least `rej_db` of rejection (inf if none). 0 if an
        in-passband spur violates spec."""
        if any(i.unfilterable for i in self.infos):
            return 0.0
        g = [i.gap for i in self.infos if not i.in_band and i.rejection >= rej_db]
        return min(g) if g else np.inf

    def mask(self, off):
        """Required filter rejection vs. frequency.

        `off` = output frequency relative to the passband's lower edge (Hz):
        the passband occupies 0..W (W = full band width); negative = below it,
        > W = above it.
        Returns (req, bad):
          req : required rejection (dB) outside the passband (0 inside)
          bad : shortfall (dB) of unfilterable spurs inside the passband
        """
        off = np.asarray(off, float)
        W = self.conv.bw
        req = np.zeros_like(off)
        bad = np.zeros_like(off)
        pad = 0.5 * np.median(np.diff(off)) if len(off) > 1 else 0.0
        for i in self.infos:
            if i.rejection <= 0:
                continue
            for side, near, far in i.segs:
                y0, y1 = (W + near, W + far) if side == "above" else (-far, -near)
                sel = (off >= y0 - pad) & (off <= y1 + pad)
                req[sel] = np.maximum(req[sel], i.rejection)
            if i.in_band and i.inband_seg is not None:
                y0, y1 = i.inband_seg
                sel = (off >= y0 - pad) & (off <= y1 + pad)
                bad[sel] = np.maximum(bad[sel], i.rejection)
        return req, bad


def analyze(conv: Converter, lo: float, table: Optional[SpurTable] = None):
    """Full spur analysis of one converter at one LO frequency."""
    lo = float(to_hz(lo))
    tb = conv.table or table or SpurTable.default()
    geo = conv.geometry(lo)
    if geo is None:
        return Analysis(conv, lo, None, [], tb.floor_dbc)
    out_lo, out_hi = sorted(geo["out"])
    in_lo, in_hi = geo["inp"]
    spurs = compute_spurs(
        (in_lo + in_hi) / 2,
        lo,
        tb,
        max_order=conv.max_order,
        rf_backoff_db=conv.rf_backoff_db,
        desired_sign=geo["sign"],
        out_center=(out_lo + out_hi) / 2,
        out_bw=conv.bw,
        in_bw=conv.bw,
    )
    infos = []
    for s in spurs:
        if s.is_desired:
            continue
        level = s.eff_dbc if conv.use_overlap_fraction else s.dbc
        if conv.direction == "up" and s.m == 1 and s.n == 1:
            level += conv.image_rejection_db  # unwanted sideband of up-conv
        co = _cochannel(conv, lo, s.m, s.n, s.sign, geo["sign"]) if s.in_band else False
        spec = conv.pb_spec if (s.in_band and not co) else conv.spec_dbc
        rej = max(0.0, spec - level)
        segs = []
        if s.f_high > out_hi:
            segs.append(("above", max(s.f_low, out_hi) - out_hi, s.f_high - out_hi))
        if s.f_low < out_lo:
            segs.append(("below", out_lo - min(s.f_high, out_lo), out_lo - s.f_low))
        gap = 0.0 if s.in_band else min((g[1] for g in segs), default=np.inf)
        seg_in = None
        if s.in_band:
            seg_in = (max(s.f_low, out_lo) - out_lo, min(s.f_high, out_hi) - out_lo)
        infos.append(
            SpurInfo(s, level, rej, s.in_band, s.in_band and rej > 0, gap, segs, co, spec, seg_in)
        )
    return Analysis(conv, lo, geo, infos, tb.floor_dbc)


def filter_report(an: Analysis, min_rej=0.0):
    """Print the spurs that need filtering (or that cannot be filtered)."""
    c = an.conv
    if an.geo is None:
        print(f"[{c.name}] LO = {fmt_freq(an.lo)} is not feasible for this setup.")
        return
    out = sorted(an.geo["out"])
    u = freq_unit([an.lo, c.if_hi, out[1], an.geo["rf"][1]])
    f = lambda v: fmt_freq(v, u)  # noqa: E731
    print(f"[{c.name}] {c.direction}-conversion, LO = {f(an.lo)}")
    print(
        f"  IF band {f(c.if_lo)}-{f(c.if_hi)} ({fmt_freq(c.bw)} wide, signal "
        f"{fmt_freq(c.sig_bw)})   RF band {f(an.geo['rf'][0])}-{f(an.geo['rf'][1])}"
    )
    print(
        f"  output passband {f(out[0])}-{f(out[1])}   spec {c.spec_dbc:g} dBc"
        + (f"   in-passband spec {c.pb_spec:g} dBc" if c.pb_spec != c.spec_dbc else "")
    )
    if not an.geo["ok"]:
        print("  ** RF band is outside the allowed rf_window **")
    rows = [i for i in an.infos if i.rejection > min_rej]
    rows.sort(key=lambda i: (not i.unfilterable, i.gap))
    if not rows:
        print("  No spurs exceed the spec: no filtering required.")
        return
    print(
        f"  {'product':<14}{'order':>5}{'spur band (' + u[1] + ')':>26}{'where':>13}"
        f"{'gap (' + u[1] + ')':>12}{'level':>8}{'need':>9}"
    )
    for i in rows:
        s = i.spur
        if i.in_band:
            where, gap = ("IN-CHANNEL" if i.co_channel else "IN-PASSBAND"), "--"
        else:
            where = i.segs[0][0] if len(i.segs) == 1 else "both"
            gap = f"{i.gap / u[0]:.3g}"
        print(
            f"  {s.label:<14}{s.order:>5}"
            f"{s.f_low / u[0]:>12.4g}-{s.f_high / u[0]:<13.4g}{where:>13}{gap:>12}"
            f"{-i.level + 0.0:>8.1f}{i.rejection:>7.1f} dB"
        )
    if any(i.unfilterable for i in rows):
        print(
            "  ** IN-PASSBAND spurs cannot be filtered: change LO / sideband / IF, "
            "or relax passband_spec_dbc if a downstream filter removes them **"
        )


# ------------------------------------------------------------------ sweep
@dataclass
class LOSweep:
    conv: Converter
    lo: np.ndarray
    allowed: np.ndarray  # geometry feasible and RF inside rf_window
    valid: np.ndarray  # allowed AND no in-passband spur violating its spec
    margin: np.ndarray  # worst in-passband margin (dB), nan if not allowed
    guard: np.ndarray  # Hz to nearest spur needing a filter
    max_rej: np.ndarray  # largest required rejection (dB)
    off: np.ndarray  # frequency grid relative to passband lower edge (Hz)
    mask: np.ndarray  # [n_lo, n_off] required rejection outside passband
    rej_levels: np.ndarray = None  # rejection thresholds (dB)
    guard_levels: np.ndarray = None  # [n_lo, n_levels] guard band per threshold
    bad: np.ndarray = None  # [n_lo, n_off] in-passband shortfall (dB)


def sweep_lo(converters, lo_values, table=None, max_offset=None, n_off=321):
    """Evaluate one or more converters over a range of LO frequencies (Hz or Quantity array).
    Pass several converters to plan a shared LO."""
    if isinstance(converters, Converter):
        converters = [converters]
    lo_values = np.asarray(to_hz(lo_values), float)
    out = []
    for c in converters:
        mo = float(to_hz(max_offset)) if max_offset else max(3 * (c.if_lo + c.if_hi) / 2, c.bw)
        off = np.linspace(-mo, c.bw + mo, n_off)
        n = len(lo_values)
        allowed = np.zeros(n, bool)
        margin = np.full(n, np.nan)
        guard = np.full(n, np.nan)
        max_rej = np.full(n, np.nan)
        mask = np.full((n, n_off), np.nan)
        bad = np.full((n, n_off), np.nan)
        levels = np.unique(np.round(c.spec_dbc * np.array([0.25, 0.5, 0.75, 1.0])))
        levels = levels[levels > 0]
        glev = np.full((n, len(levels)), np.nan)
        for k, lo in enumerate(lo_values):
            a = analyze(c, lo, table)
            if a.geo is None or not a.geo["ok"]:
                continue
            allowed[k] = True
            margin[k] = a.margin
            guard[k] = min(a.guard, mo)
            max_rej[k] = a.max_rej
            mask[k], bad[k] = a.mask(off)
            glev[k] = [min(a.guard_at(L), mo) for L in levels]
        valid = allowed & (np.nan_to_num(margin, nan=-1) >= 0)
        out.append(
            LOSweep(
                c, lo_values, allowed, valid, margin, guard, max_rej, off, mask, levels, glev, bad
            )
        )
    return out


def best_los(sweeps, top=5, verbose=True):
    """Contiguous LO windows that are valid for ALL converters, best first
    (largest guard band, then lowest required rejection)."""
    sweeps = [sweeps] if isinstance(sweeps, LOSweep) else list(sweeps)
    lo = sweeps[0].lo
    valid = np.all([s.valid for s in sweeps], axis=0)
    guard = np.min([np.nan_to_num(s.guard, nan=-1) for s in sweeps], axis=0)
    rej = np.max([np.nan_to_num(s.max_rej, nan=1e9) for s in sweeps], axis=0)
    wins, start = [], None
    for k in range(len(lo)):
        if valid[k] and start is None:
            start = k
        if start is not None and (not valid[k] or k == len(lo) - 1):
            end = k if valid[k] else k - 1
            idx = np.arange(start, end + 1)
            best = idx[np.lexsort((rej[idx], -guard[idx]))[0]]
            wins.append(
                dict(
                    lo_from=lo[start],
                    lo_to=lo[end],
                    best_lo=lo[best],
                    guard=guard[best],
                    max_rej=rej[best],
                )
            )
            start = None
    wins.sort(key=lambda w: (-w["guard"], w["max_rej"]))
    wins = wins[:top]
    if verbose:
        if not wins:
            print("No LO in the swept range is valid for all converters.")
            for sw_ in sweeps:
                if sw_.valid.any():
                    r = sw_.lo[sw_.valid]
                    print(
                        f"  {sw_.conv.name}: valid on its own for LO "
                        f"{fmt_freq(r.min())} to {fmt_freq(r.max())}"
                    )
                elif sw_.allowed.any():
                    print(
                        f"  {sw_.conv.name}: LO feasible but every feasible "
                        "LO has an in-passband spur violating spec"
                    )
                else:
                    print(
                        f"  {sw_.conv.name}: no feasible LO (check rf_window / sideband / LO range)"
                    )
            print(
                "  Try the other sideband, a different IF, a wider LO range, "
                "a looser spec, or separate LOs."
            )
        else:
            names = " + ".join(s.conv.name for s in sweeps)
            u = freq_unit(lo[-1])
            print(f"Valid LO windows for {names}:")
            print(
                f"  {'LO window (' + u[1] + ')':>24}{'best LO':>11}{'guard (' + u[1] + ')':>13}"
                f"{'max rej (dB)':>14}"
            )
            for w in wins:
                print(
                    f"  {w['lo_from'] / u[0]:>11.6g} - {w['lo_to'] / u[0]:<10.6g}"
                    f"{w['best_lo'] / u[0]:>11.6g}{w['guard'] / u[0]:>13.6g}"
                    f"{w['max_rej']:>14.1f}"
                )
    return wins


# ---------------------------------------------------------------- plotting
def _runs(flag, x):
    if len(x) < 2:
        return
    dx = np.median(np.diff(x)) / 2
    start = None
    for i, f in enumerate(flag):
        if f and start is None:
            start = i
        if start is not None and (not f or i == len(flag) - 1):
            end = i if f else i - 1
            yield x[start] - dx, x[end] + dx
            start = None


def plot_lo_sweep(sweeps, zoom=True, margin_cap=20.0):
    """LO planning plot. One column per converter, three aligned rows (see the
    subplot titles). Row 3 is drawn in frequency relative to the passband: the
    gold strip is the passband (width = full IF band), where nothing can be
    filtered; red marks LOs where a spur lands inside it and fails the spec.
    Colors outside the strip show the filter rejection required at that
    frequency. Green background = LO valid, red = fails, grey = infeasible.
    zoom=True crops the x-axis to each converter's feasible LO range."""
    import matplotlib.pyplot as plt
    from matplotlib.colors import ListedColormap
    from matplotlib.patches import Patch

    sweeps = [sweeps] if isinstance(sweeps, LOSweep) else list(sweeps)
    n = len(sweeps)
    fig = plt.figure(figsize=(7.5 * n, 10.5), constrained_layout=True)
    gs = fig.add_gridspec(3, 2 * n, width_ratios=[1, 0.03] * n, height_ratios=[1, 1.3, 2])
    wins = best_los(sweeps, top=1, verbose=False)
    best = wins[0]["best_lo"] if wins else None
    red = ListedColormap(["tab:red"])

    for j, s in enumerate(sweeps):
        div, un = freq_unit([s.lo.max(), s.conv.if_hi, s.conv.bw])
        W = s.conv.bw / div  # display units from here on
        off = s.off / div
        a1 = fig.add_subplot(gs[0, 2 * j])
        a2 = fig.add_subplot(gs[1, 2 * j], sharex=a1)
        a3 = fig.add_subplot(gs[2, 2 * j], sharex=a1)
        cax = fig.add_subplot(gs[2, 2 * j + 1])
        x = s.lo / div
        bad_lo = s.allowed & ~s.valid
        col_best = best
        if col_best is None:
            w1 = best_los(s, top=1, verbose=False)
            col_best = w1[0]["best_lo"] if w1 else None
        if col_best is not None:
            col_best = col_best / div
        for ax in (a1, a2, a3):
            for x0, x1 in _runs(~s.allowed, x):
                ax.axvspan(x0, x1, color="0.6", alpha=0.25, lw=0)
            for x0, x1 in _runs(bad_lo, x):
                ax.axvspan(x0, x1, color="tab:red", alpha=0.15, lw=0)
            for x0, x1 in _runs(s.valid, x):
                ax.axvspan(x0, x1, color="tab:green", alpha=0.12, lw=0)
            if col_best is not None:
                ax.axvline(col_best, color="k", ls=":", lw=1)
            ax.grid(alpha=0.25)

        sig = (
            f", signal {fmt_freq(s.conv.sig_bw)} in {fmt_freq(s.conv.bw)} band"
            if s.conv.sig_bw < s.conv.bw
            else f", {fmt_freq(s.conv.bw)} band"
        )
        # Row 1: in-passband margin
        m = np.clip(s.margin, -margin_cap, margin_cap)
        a1.plot(x, m, color="tab:blue")
        a1.fill_between(x, 0, m, where=m < 0, color="tab:red", alpha=0.4)
        a1.axhline(0, color="k", lw=0.8)
        a1.set_ylim(-margin_cap * 1.05, margin_cap * 1.05)
        a1.set_ylabel("margin (dB)")
        a1.set_title(
            f"{s.conv.name} ({s.conv.direction}, {s.conv.sideband} "
            f"sideband, spec {s.conv.spec_dbc:g} dBc{sig})\n"
            "1. Spur inside the passband: margin vs. spec (<0 fails)",
            fontsize=9,
            loc="left",
        )

        # Row 2: guard band per rejection level
        if s.rej_levels is not None and len(s.rej_levels):
            cols = plt.cm.Blues(np.linspace(0.4, 1.0, len(s.rej_levels)))
            for k, lvl in enumerate(s.rej_levels):
                a2.plot(
                    x,
                    s.guard_levels[:, k] / div,
                    color=cols[k],
                    label=f"spur needing >= {lvl:g} dB",
                )
            a2.legend(fontsize=7, loc="best")
        a2.set_ylabel(f"guard band ({un})")
        a2.set_title(
            "2. Distance from passband edge to nearest spur needing "
            "that much rejection (higher = easier filter)",
            fontsize=9,
            loc="left",
        )

        # Row 3: required rejection vs frequency relative to the passband
        req = np.ma.masked_invalid(s.mask.T)
        inside = (off >= 0) & (off <= W)
        req = np.ma.masked_where(
            np.broadcast_to(inside[:, None], req.shape) | np.ma.getmaskarray(req), req
        )
        a3.axhspan(0, W, color="gold", alpha=0.35, lw=0, zorder=0)
        pc = a3.pcolormesh(
            x,
            off,
            req,
            shading="nearest",
            cmap="magma_r",
            vmin=0,
            vmax=max(s.conv.spec_dbc, 1),
            zorder=1,
        )
        badm = np.ma.masked_where(~(np.nan_to_num(s.bad.T) > 0), s.bad.T)
        a3.pcolormesh(x, off, badm, shading="nearest", cmap=red, alpha=0.85, zorder=2)
        a3.axhline(0, color="k", lw=0.6)
        a3.axhline(W, color="k", lw=0.6)
        a3.set_ylabel(f"frequency relative to passband ({un})\n0 = lower edge, {W:g} = upper edge")
        a3.set_xlabel(f"LO frequency ({un})")
        a3.set_title(
            "3. Required filter rejection vs. frequency (gold = passband, cannot be filtered)",
            fontsize=9,
            loc="left",
        )
        fig.colorbar(pc, cax=cax, label="required rejection (dB)")
        plt.setp(a1.get_xticklabels(), visible=False)
        plt.setp(a2.get_xticklabels(), visible=False)

        if zoom and s.allowed.any():
            xs = x[s.allowed]
            pad = max(0.08 * (xs.max() - xs.min()), 2 * np.median(np.diff(x)))
            a1.set_xlim(xs.min() - pad, xs.max() + pad)

    fig.legend(
        handles=[
            Patch(fc="tab:green", alpha=0.3, label="LO valid"),
            Patch(fc="tab:red", alpha=0.3, label="spur in passband fails spec"),
            Patch(fc="0.6", alpha=0.4, label="infeasible / outside RF window"),
            Patch(fc="gold", alpha=0.5, label="passband (no filtering possible)"),
            Patch(fc="tab:red", alpha=0.85, label="failing in-passband spur"),
        ],
        loc="outside lower center",
        ncol=3 if n == 1 else 5,
        fontsize=8,
    )
    return fig


def plot_filter_mask(an: Analysis, ax=None, max_offset=None, n=1601, label_top=12):
    """Required filter rejection vs. frequency for one LO. The gold strip is the
    passband (full IF band width): nothing there can be filtered. Blue shows the
    rejection required outside it; red hatched bars are spurs landing INSIDE the
    passband (their height is the shortfall vs. spec, which no filter fixes)."""
    import matplotlib.pyplot as plt

    if ax is None:
        _, ax = plt.subplots(figsize=(11, 4.5))
    c = an.conv
    W = c.bw
    mo = float(to_hz(max_offset)) if max_offset else max(3 * (c.if_lo + c.if_hi) / 2, W)
    off_hz = np.linspace(-mo, W + mo, n)
    req, bad = an.mask(off_hz)
    div, un = freq_unit([mo, W])
    off, Wd = off_hz / div, W / div
    ax.axvspan(
        0, Wd, color="gold", alpha=0.35, label=f"passband ({fmt_freq(W)}): cannot be filtered"
    )
    ax.fill_between(off, 0, req, step="mid", color="tab:blue", alpha=0.35)
    ax.step(off, req, where="mid", color="tab:blue", label="required rejection")
    if np.any(bad > 0):
        ax.fill_between(
            off,
            0,
            bad,
            step="mid",
            color="tab:red",
            alpha=0.5,
            hatch="//",
            label="spur inside passband (fails spec)",
        )
    top = sorted((i for i in an.infos if i.rejection > 0), key=lambda i: -i.rejection)[:label_top]
    for i in top:
        for side, near, far in i.segs:
            y0, y1 = (W + near, W + far) if side == "above" else (-far, -near)
            ax.annotate(
                f"{i.spur.m}x{i.spur.n}",
                ((y0 + y1) / 2 / div, i.rejection),
                fontsize=7,
                rotation=90,
                ha="center",
                va="bottom",
            )
        if i.in_band and i.inband_seg is not None:
            ax.annotate(
                f"{i.spur.m}x{i.spur.n}",
                (sum(i.inband_seg) / 2 / div, i.rejection),
                fontsize=7,
                rotation=90,
                ha="center",
                va="bottom",
            )
    ax.set_ylim(0, max(c.spec_dbc, req.max(), bad.max()) * 1.2 + 1)
    ax.set_xlabel(f"output frequency relative to passband lower edge ({un})")
    ax.set_ylabel("required rejection (dB)")
    lo_, hi_ = sorted(an.geo["out"])
    ax.set_title(
        f"Filter mask: {c.name}, LO = {fmt_freq(an.lo)}  "
        f"(passband {fmt_freq(lo_)} to {fmt_freq(hi_)})"
    )
    ax.grid(alpha=0.3)
    ax.legend(loc="upper right", fontsize=8)
    return ax


def plot_spur_map(
    conv: Converter, lo: float, table=None, signal_center=None, show_dbc=None, ax=None
):
    """Classic spur chart for one converter at one LO (see
    mixer_spurs.plot_spur_chart): x = mixer input frequency, y = output
    frequency, input range (blue), output range (gold) and their box. Product
    lines crossing the box are in-band spurs.

    If the converter has signal_bw set, a purple dashed signal box is drawn at
    signal_center (an IF or RF frequency, Hz or Quantity; default: middle of the band)."""
    lo = float(to_hz(lo))
    tb = conv.table or table or SpurTable.default()
    geo = conv.geometry(lo)
    if geo is None:
        raise ValueError("LO not feasible for this converter")
    sbw = conv.signal_bw if (conv.signal_bw is not None and conv.signal_bw < conv.bw) else None
    return plot_spur_chart(
        tb,
        lo,
        geo["inp"],
        tuple(sorted(geo["out"])),
        geo["sign"],
        signal_bw=sbw,
        signal_center=signal_center if sbw else None,
        spec_dbc=conv.spec_dbc,
        max_order=conv.max_order,
        rf_backoff_db=conv.rf_backoff_db,
        show_dbc=show_dbc,
        ax=ax,
    )
